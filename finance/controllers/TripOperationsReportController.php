<?php

namespace Finance\Controllers;

/*
|--------------------------------------------------------------------------
| ERROR REPORTING
|--------------------------------------------------------------------------
*/

ini_set('display_errors', 1);

ini_set('display_startup_errors', 1);

error_reporting(E_ALL);

/*
|--------------------------------------------------------------------------
| LOAD SERVICE
|--------------------------------------------------------------------------
*/

require_once __DIR__ .
    '/../services/TripOperationsReportService.php';

use Finance\Services\TripOperationsReportService;

/*
|--------------------------------------------------------------------------
| CONTROLLER
|--------------------------------------------------------------------------
*/

class TripOperationsReportController
{
    /*
    |--------------------------------------------------------------------------
    | MAX FILE SIZE
    |--------------------------------------------------------------------------
    */

    private const MAX_FILE_SIZE =
        10 * 1024 * 1024;

    /*
    |--------------------------------------------------------------------------
    | ALLOWED MIME TYPES
    |--------------------------------------------------------------------------
    */

    private const ALLOWED_MIME_TYPES = [

        /*
        |--------------------------------------------------------------------------
        | DOCUMENTS
        |--------------------------------------------------------------------------
        */

        'application/pdf',

        'text/plain',

        'application/msword',

        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',

        /*
        |--------------------------------------------------------------------------
        | EXCEL / CSV
        |--------------------------------------------------------------------------
        */

        'text/csv',

        'application/csv',

        'application/vnd.ms-excel',

        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',

        /*
        |--------------------------------------------------------------------------
        | IMAGES
        |--------------------------------------------------------------------------
        */

        'image/jpeg',

        'image/png',

        'image/webp'
    ];

    /*
    |--------------------------------------------------------------------------
    | SERVICE
    |--------------------------------------------------------------------------
    */

    private TripOperationsReportService $service;

    /*
    |--------------------------------------------------------------------------
    | CONSTRUCTOR
    |--------------------------------------------------------------------------
    */

    public function __construct()
    {
        $this->service =
            new TripOperationsReportService();
    }

    /*
    |--------------------------------------------------------------------------
    | SAVE
    |--------------------------------------------------------------------------
    */

    public function save(): void
    {
        /*
        |--------------------------------------------------------------------------
        | REQUEST VALIDATION
        |--------------------------------------------------------------------------
        */

        if($_SERVER['REQUEST_METHOD'] !== 'POST'){

            http_response_code(405);

            exit('Method Not Allowed');
        }

        /*
        |--------------------------------------------------------------------------
        | GET TRIPS
        |--------------------------------------------------------------------------
        */

        $trips =
            $_POST['trips']
            ?? [];

        /*
        |--------------------------------------------------------------------------
        | VALIDATE TRIPS
        |--------------------------------------------------------------------------
        */

        if(
            !is_array($trips)
            ||
            empty($trips)
        ){

            $this->redirect(
                'no_trips'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | CLEAN TRIPS
        |--------------------------------------------------------------------------
        */

        $cleanTrips = [];

        foreach($trips as $trip){

            /*
            |--------------------------------------------------------------------------
            | SKIP INVALID ROWS
            |--------------------------------------------------------------------------
            */

            if(!is_array($trip)){

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | CLEAN DATA
            |--------------------------------------------------------------------------
            */

            $cleanTrips[] = [

                'route_id' =>

                    (int)(
                        $trip['route_id']
                        ?? 0
                    ),

                'bus_id' =>

                    (int)(
                        $trip['bus_id']
                        ?? 0
                    ),

                'driver_id' =>

                    (int)(
                        $trip['driver_id']
                        ?? 0
                    ),

                'inspector_id' =>

                    (int)(
                        $trip['inspector_id']
                        ?? 0
                    ),

                'trip_date' =>

                    trim(
                        $trip['trip_date']
                        ?? ''
                    ),

                'passenger_count' =>

                    (int)(
                        $trip['passenger_count']
                        ?? 0
                    ),

                'total_revenue' =>

                    (float)(
                        $trip['total_revenue']
                        ?? 0
                    ),

                'fuel_cost' =>

                    (float)(
                        $trip['fuel_cost']
                        ?? 0
                    ),

                'other_expenses' =>

                    (float)(
                        $trip['other_expenses']
                        ?? 0
                    ),

                'odometer' =>

                    (float)(
                        $trip['odometer']
                        ?? 0
                    ),

                'notes' =>

                    trim(
                        $trip['notes']
                        ?? ''
                    )
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | AI NOTES
        |--------------------------------------------------------------------------
        */

        $aiNotes =
            trim(
                $_POST['ai_analysis_notes']
                ?? ''
            );

        /*
        |--------------------------------------------------------------------------
        | PROCESS FILES
        |--------------------------------------------------------------------------
        */

        $allFiles =
            $this->collectFiles();

        /*
        |--------------------------------------------------------------------------
        | SAVE TO SERVICE
        |--------------------------------------------------------------------------
        */

        try{

            $saved =

                $this->service
                ->saveTrips(

                    $cleanTrips,

                    $allFiles,

                    $aiNotes
                );

            /*
            |--------------------------------------------------------------------------
            | SUCCESS
            |--------------------------------------------------------------------------
            */

            if($saved){

                $this->redirect(
                    'success'
                );
            }

            /*
            |--------------------------------------------------------------------------
            | FAILED SAVE
            |--------------------------------------------------------------------------
            */

            $this->redirect(
                'save_failed'
            );

        }catch(\Throwable $e){

            /*
            |--------------------------------------------------------------------------
            | LOG ERROR
            |--------------------------------------------------------------------------
            */

            error_log(

                '[TripOperationsReportController] '

                .

                $e->getMessage()
            );

            /*
            |--------------------------------------------------------------------------
            | REDIRECT ERROR
            |--------------------------------------------------------------------------
            */

            $this->redirect(
                'server_error'
            );
        }
    }

    /*
    |--------------------------------------------------------------------------
    | COLLECT FILES
    |--------------------------------------------------------------------------
    */

    private function collectFiles(): array
    {
        $allFiles = [];

        /*
        |--------------------------------------------------------------------------
        | FILE GROUPS
        |--------------------------------------------------------------------------
        */

        $fileGroups = [

            'evidence_documents',

            'evidence_reports',

            'evidence_images'
        ];

        /*
        |--------------------------------------------------------------------------
        | LOOP GROUPS
        |--------------------------------------------------------------------------
        */

        foreach($fileGroups as $group){

            if(
                !isset($_FILES[$group])
                ||
                empty($_FILES[$group]['name'][0])
            ){

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | LOOP FILES
            |--------------------------------------------------------------------------
            */

            foreach(

                $_FILES[$group]['name']

                as $index => $name
            ){

                /*
                |--------------------------------------------------------------------------
                | BUILD FILE
                |--------------------------------------------------------------------------
                */

                $file = [

                    'name' =>

                        $_FILES[$group]['name'][$index]
                        ?? '',

                    'tmp_name' =>

                        $_FILES[$group]['tmp_name'][$index]
                        ?? '',

                    'error' =>

                        $_FILES[$group]['error'][$index]
                        ?? UPLOAD_ERR_NO_FILE,

                    'size' =>

                        $_FILES[$group]['size'][$index]
                        ?? 0,

                    'type' =>

                        $_FILES[$group]['type'][$index]
                        ?? ''
                ];

                /*
                |--------------------------------------------------------------------------
                | VALIDATE FILE
                |--------------------------------------------------------------------------
                */

                if(
                    !$this->isValidFile(
                        $file
                    )
                ){

                    continue;
                }

                /*
                |--------------------------------------------------------------------------
                | ADD FILE
                |--------------------------------------------------------------------------
                */

                $allFiles[] = $file;
            }
        }

        return $allFiles;
    }

    /*
    |--------------------------------------------------------------------------
    | VALIDATE FILE
    |--------------------------------------------------------------------------
    */

    private function isValidFile(
        array $file
    ): bool
    {
        /*
        |--------------------------------------------------------------------------
        | CHECK ERROR
        |--------------------------------------------------------------------------
        */

        if(
            ($file['error'] ?? 1)
            !==
            UPLOAD_ERR_OK
        ){

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | CHECK FILE EXISTS
        |--------------------------------------------------------------------------
        */

        if(
            empty($file['tmp_name'])
            ||
            !file_exists(
                $file['tmp_name']
            )
        ){

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | CHECK SIZE
        |--------------------------------------------------------------------------
        */

        if(
            ($file['size'] ?? 0)
            >
            self::MAX_FILE_SIZE
        ){

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | MIME TYPE
        |--------------------------------------------------------------------------
        */

        $mimeType =
            mime_content_type(
                $file['tmp_name']
            );

        /*
        |--------------------------------------------------------------------------
        | CHECK MIME
        |--------------------------------------------------------------------------
        */

        if(
            !in_array(

                $mimeType,

                self::ALLOWED_MIME_TYPES,

                true
            )
        ){

            return false;
        }

        return true;
    }

    /*
    |--------------------------------------------------------------------------
    | REDIRECT
    |--------------------------------------------------------------------------
    */

    private function redirect(
        string $status
    ): void
    {
        header(

            'Location: /finance/financialreports?status='

            .

            urlencode($status)
        );

        exit;
    }
}

/*
|--------------------------------------------------------------------------
| AUTO RUN
|--------------------------------------------------------------------------
*/

if(
    $_SERVER['REQUEST_METHOD']
    ===
    'POST'
){

    $controller =

        new TripOperationsReportController();

    $controller->save();
}