<script>
function getDevice() {
    const ua = navigator.userAgent;

    if (/iPhone/i.test(ua)) return ["Mobile Device", "iOS"];
    if (/Android/i.test(ua)) return ["Mobile Device", "Android"];
    if (/Mac/i.test(ua)) return ["Laptop", "macOS"];
    if (/Windows/i.test(ua)) return ["Desktop", "Windows"];
    return ["Unknown", "Unknown"];
}

function downloadReport(btn) {
    const row = btn.closest("tr");

    const now = new Date();
    const date = now.toLocaleDateString("en-GB", {
        day: "2-digit",
        month: "long",
        year: "numeric",
    });
    const time = now.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });

    const device = getDevice();

    row.children[6].innerHTML = `
        <span class="audit-main">Current User (Admin)</span>
        <span class="audit-sub">${date} ${time}</span>
    `;

    row.children[7].innerHTML = `
        <span class="audit-main">${device[0]}</span>
        <span class="audit-sub">${device[1]}</span>
    `;

    row.parentNode.prepend(row);
}
</script>