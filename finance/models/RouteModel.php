<?php

namespace Finance\Models;

/*
|--------------------------------------------------------------------------
| DATABASE
|--------------------------------------------------------------------------
*/

require_once __DIR__ .
    '/../../app/Core/Database.php';

use App\Core\Database;

class RouteModel
{
    /*
    |--------------------------------------------------------------------------
    | GET ALL TERMINALS
    |--------------------------------------------------------------------------
    */

    public function getAllRoutes(): array
    {
        try{

            /*
            |--------------------------------------------------------------------------
            | DATABASE
            |--------------------------------------------------------------------------
            */

            $db =
                Database::get();

            /*
            |--------------------------------------------------------------------------
            | SQL
            |--------------------------------------------------------------------------
            */

            $sql = "

                SELECT

                    id,
                    terminal_code,
                    terminal_name,
                    city,
                    province,
                    latitude,
                    longitude,
                    status

                FROM terminals

                ORDER BY terminal_name ASC

            ";

            /*
            |--------------------------------------------------------------------------
            | PREPARE
            |--------------------------------------------------------------------------
            */

            $stmt =
                $db->prepare($sql);

            /*
            |--------------------------------------------------------------------------
            | EXECUTE
            |--------------------------------------------------------------------------
            */

            $stmt->execute();

            /*
            |--------------------------------------------------------------------------
            | RETURN DATA
            |--------------------------------------------------------------------------
            */

            return $stmt->fetchAll(
                \PDO::FETCH_ASSOC
            );

        }catch(\Exception $e){

            /*
            |--------------------------------------------------------------------------
            | FAIL SAFE
            |--------------------------------------------------------------------------
            */

            return [];
        }
    }

    /*
    |--------------------------------------------------------------------------
    | GET ACTIVE TERMINALS
    |--------------------------------------------------------------------------
    */

    public function getRoutesByStatus(
        string $status
    ): array
    {
        try{

            /*
            |--------------------------------------------------------------------------
            | DATABASE
            |--------------------------------------------------------------------------
            */

            $db =
                Database::get();

            /*
            |--------------------------------------------------------------------------
            | SQL
            |--------------------------------------------------------------------------
            */

            $sql = "

                SELECT

                    id,
                    terminal_code,
                    terminal_name,
                    city,
                    province,
                    latitude,
                    longitude,
                    status

                FROM terminals

                WHERE status = :status

                ORDER BY terminal_name ASC

            ";

            /*
            |--------------------------------------------------------------------------
            | PREPARE
            |--------------------------------------------------------------------------
            */

            $stmt =
                $db->prepare($sql);

            /*
            |--------------------------------------------------------------------------
            | BIND
            |--------------------------------------------------------------------------
            */

            $stmt->bindValue(

                ':status',

                $status
            );

            /*
            |--------------------------------------------------------------------------
            | EXECUTE
            |--------------------------------------------------------------------------
            */

            $stmt->execute();

            /*
            |--------------------------------------------------------------------------
            | RETURN
            |--------------------------------------------------------------------------
            */

            return $stmt->fetchAll(
                \PDO::FETCH_ASSOC
            );

        }catch(\Exception $e){

            return [];
        }
    }
}