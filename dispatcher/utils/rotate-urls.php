<?php
// Dispatcher URL hash rotation script
// Run: php dispatcher/utils/rotate-urls.php
// Generates new 32-char hex hashes, moves current to previous with a 24-hour
// grace so long-lived pages (mobile PWAs) keep working across the operating day.

$configPath = __DIR__ . '/urls.php';
$urls = file_exists($configPath) ? require $configPath : [];

$now = time();

// Move current hashes to previous with expiry
$previous = $urls['previous'] ?? [];
if (isset($urls['login'])) {
    $previous[] = [
        'login' => $urls['login'],
        'dashboard' => $urls['dashboard'],
        'api' => $urls['api'],
        'expires_at' => $now + 86400,
    ];
}
// Clean expired previous entries
$previous = array_filter($previous, fn($p) => ($p['expires_at'] ?? 0) >= $now);
$previous = array_values($previous); // re-index

// Generate new hashes
$urls = [
    'login' => bin2hex(random_bytes(16)),
    'dashboard' => bin2hex(random_bytes(16)),
    'api' => bin2hex(random_bytes(16)),
    'generated_at' => $now,
    'previous' => $previous,
];

$content = '<?php' . "\n";
$content .= '// Dispatcher obfuscated URL mappings' . "\n";
$content .= '// Auto-generated by rotate-urls.php — do not edit manually' . "\n";
$content .= '// Format: [\'login\' => \'<hash>\', \'dashboard\' => \'<hash>\', \'api\' => \'<hash>\', \'generated_at\' => <timestamp>, \'previous\' => [...]]' . "\n";
$content .= '// Each previous entry: [\'login\' => \'<hash>\', \'dashboard\' => \'<hash>\', \'api\' => \'<hash>\', \'expires_at\' => <timestamp>]' . "\n\n";
$content .= 'return ' . var_export($urls, true) . ";\n";

file_put_contents($configPath, $content);

echo "New dispatcher URLs generated:\n";
echo "  Login:     /dispatcher/{$urls['login']}\n";
echo "  Dashboard: /dispatcher/{$urls['dashboard']}\n";
echo "  API:       /dispatcher/api_{$urls['api']}/{endpoint}\n";
echo "\nPrevious URLs remain valid for 24 hours.\n";
