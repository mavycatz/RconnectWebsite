<?php

declare(strict_types=1);

namespace Admin\Services;

require_once $_SERVER['DOCUMENT_ROOT']
. '/vendor/autoload.php';
require_once $_SERVER['DOCUMENT_ROOT']
. '/app/Views/pdf/template.php';
require_once __DIR__ . '/ReportCenterPresentationService.php';

use Dompdf\Dompdf;
use Dompdf\Options;

class PDFService
{
    private const MAX_TABLE_ROWS = 500;

    private Dompdf $dompdf;

    public function __construct()
    {
        $options = new Options();

        $options->set('isRemoteEnabled', true);
        $options->set('isHtml5ParserEnabled', true);

        $this->dompdf = new Dompdf($options);
    }

    private function e($value): string
    {
        return htmlspecialchars((string)$value, ENT_QUOTES, 'UTF-8');
    }

    private function fmtValue($value, string $type): string
    {
        $raw = trim((string)($value ?? ''));
        if ($raw === '' || str_starts_with($raw, '0000-00-00')) {
            return '—';
        }
        switch ($type) {
            case 'money':
                return $this->e('₱' . number_format((float)$raw, 2));
            case 'date':
                try {
                    $dt = new \DateTime($raw, new \DateTimeZone('Asia/Manila'));
                    return $this->e($dt->format('M j, Y'));
                } catch (\Throwable $e) {
                    return $this->e($raw);
                }
            case 'datetime':
                try {
                    $dt = new \DateTime($raw, new \DateTimeZone('Asia/Manila'));
                    return $this->e($dt->format('M j, Y g:i A'));
                } catch (\Throwable $e) {
                    return $this->e($raw);
                }
            default:
                return $this->e($raw);
        }
    }

    private function deltaText(?float $delta): string
    {
        if ($delta === null) {
            return 'n/a';
        }
        $sign = $delta > 0 ? '+' : '';
        $class = $delta > 0 ? 'green' : ($delta < 0 ? 'red' : '');
        $text = $this->e($sign . number_format($delta, 1) . '%');
        return $class !== '' ? '<span class="' . $class . '">' . $text . '</span>' : $text;
    }

    private function renderMeta(array $report): string
    {
        $rows = '';

        $meta = $report['meta'] ?? [];
        $metaPairs = [
            'Report type' => (string)($meta['type_label'] ?? ''),
            'Covered period' => (string)($meta['period_label'] ?? 'All records'),
            'Covered dates' => (string)($meta['range_label'] ?? ''),
            'Generated' => (string)($meta['generated_at'] ?? ''),
            'Generated by' => (string)($meta['generated_by'] ?? ''),
            'Records' => (string)($meta['record_count'] ?? ''),
        ];

        foreach ($metaPairs as $label => $value) {
            if (trim($value) === '') {
                continue;
            }
            $rows .= '<tr><td style="width:32%;font-weight:bold;background:#f6f9f6;">' . $this->e($label) . '</td><td>' . $this->e($value) . '</td></tr>';
        }

        $filters = $meta['filters'] ?? [];
        if ($filters) {
            $parts = [];
            foreach ($filters as $filter) {
                $parts[] = $this->e((string)($filter['label'] ?? '')) . ': ' . $this->e((string)($filter['value'] ?? ''));
            }
            $rows .= '<tr><td style="font-weight:bold;background:#f6f9f6;">Applied filters</td><td>' . implode(' &nbsp;·&nbsp; ', $parts) . '</td></tr>';
        }

        return $rows;
    }

    private function renderKpis(array $report): string
    {
        $kpis = $report['kpis'] ?? [];
        if (!$kpis) {
            return '';
        }

        $cards = '';
        foreach ($kpis as $kpi) {
            $cards .= '
                <div class="stats-card" style="width:31%;margin-bottom:8px;">
                    <div class="stats-title">' . $this->e($kpi['label'] ?? '') . '</div>
                    <div class="stats-value">' . $this->e($kpi['value'] ?? '') . '</div>
                    ' . (trim((string)($kpi['hint'] ?? '')) !== '' ? '<div style="font-size:9px;color:#666;margin-top:4px;">' . $this->e($kpi['hint']) . '</div>' : '') . '
                </div>';
        }

        return '
        <div class="section">
            <div class="section-title">Key Metrics</div>
            <div class="stats-grid">' . $cards . '</div>
        </div>';
    }

    private function renderComparison(array $report): string
    {
        $comparison = $report['comparison'] ?? null;
        if (!$comparison || empty($comparison['entries'])) {
            return '';
        }

        $rows = '';
        foreach ($comparison['entries'] as $entry) {
            $rows .= '<tr>'
                . '<td>' . $this->e($entry['label'] ?? '') . '</td>'
                . '<td style="text-align:right;">' . $this->e($entry['current'] ?? '') . '</td>'
                . '<td style="text-align:right;">' . $this->e($entry['previous'] ?? '') . '</td>'
                . '<td style="text-align:right;">' . $this->deltaText(isset($entry['delta_pct']) ? (float)$entry['delta_pct'] : null) . '</td>'
                . '</tr>';
        }

        return '
        <div class="section">
            <div class="section-title">Comparison with Previous Period</div>
            <div style="font-size:10px;color:#666;margin-bottom:4px;">' . $this->e($comparison['label'] ?? '') . '</div>
            <table>
                <thead><tr><th>Measure</th><th style="text-align:right;">Current</th><th style="text-align:right;">Previous</th><th style="text-align:right;">Change</th></tr></thead>
                <tbody>' . $rows . '</tbody>
            </table>
        </div>';
    }

    private function renderTable(string $title, array $columns, array $rows): string
    {
        if (!$columns) {
            return '';
        }

        $head = '';
        foreach ($columns as $column) {
            $head .= '<th>' . $this->e($column['label'] ?? $column['key'] ?? '') . '</th>';
        }

        $body = '';
        $shown = 0;
        foreach ($rows as $row) {
            if ($shown >= self::MAX_TABLE_ROWS) {
                break;
            }
            $cells = '';
            foreach ($columns as $column) {
                $cells .= '<td>' . $this->fmtValue($row[$column['key'] ?? ''] ?? null, (string)($column['type'] ?? 'text')) . '</td>';
            }
            $body .= '<tr>' . $cells . '</tr>';
            $shown++;
        }

        if ($shown === 0) {
            $body = '<tr><td colspan="' . count($columns) . '" style="text-align:center;color:#666;">No records matched the applied filters.</td></tr>';
        }

        $note = '';
        if (count($rows) > self::MAX_TABLE_ROWS) {
            $note = '<div style="font-size:9px;color:#666;margin-top:4px;">Showing the first ' . self::MAX_TABLE_ROWS . ' of ' . count($rows) . ' records. Export to CSV for the complete set.</div>';
        }

        return '
        <div class="section">
            <div class="section-title">' . $this->e($title) . '</div>
            <table>
                <thead><tr>' . $head . '</tr></thead>
                <tbody>' . $body . '</tbody>
            </table>
            ' . $note . '
        </div>';
    }

    private function renderDistributions(array $report): string
    {
        $distributions = $report['distributions'] ?? [];
        if (!$distributions) {
            return '';
        }

        $html = '<div class="section"><div class="section-title">Breakdowns</div>';
        foreach ($distributions as $group) {
            $counts = $group['counts'] ?? [];
            if (!$counts) {
                continue;
            }
            $total = array_sum($counts);
            $html .= '<div style="font-size:10px;font-weight:bold;margin:8px 0 4px;">' . $this->e($group['label'] ?? '') . '</div>';
            $html .= '<table><thead><tr><th>Value</th><th style="text-align:right;">Records</th><th style="text-align:right;">Share</th></tr></thead><tbody>';
            foreach ($counts as $value => $count) {
                $share = $total > 0 ? round(((int)$count / $total) * 100, 1) : 0;
                $html .= '<tr><td>' . $this->e((string)$value) . '</td><td style="text-align:right;">' . (int)$count . '</td><td style="text-align:right;">' . $share . '%</td></tr>';
            }
            $html .= '</tbody></table>';
        }
        $html .= '</div>';
        return $html;
    }

    private function renderTrends(array $report): string
    {
        $trends = $report['trends'] ?? [];
        if (!$trends) {
            return '';
        }

        $html = '<div class="section"><div class="section-title">Trends</div>';
        foreach ($trends as $trend) {
            $points = $trend['points'] ?? [];
            if (!$points) {
                continue;
            }
            $html .= '<div style="font-size:10px;font-weight:bold;margin:8px 0 4px;">' . $this->e($trend['label'] ?? '') . '</div>';
            $html .= '<table><thead><tr><th>Date</th><th style="text-align:right;">Records</th>'
                . ($trend['measure_label'] ? '<th style="text-align:right;">' . $this->e((string)$trend['measure_label']) . '</th>' : '')
                . '</tr></thead><tbody>';
            foreach ($points as $day => $point) {
                $html .= '<tr><td>' . $this->e((string)$day) . '</td><td style="text-align:right;">' . (int)($point['count'] ?? 0) . '</td>';
                if ($trend['measure_label']) {
                    $html .= '<td style="text-align:right;">' . $this->e('₱' . number_format((float)($point['sum'] ?? 0), 2)) . '</td>';
                }
                $html .= '</tr>';
            }
            $html .= '</tbody></table>';
        }
        $html .= '</div>';
        return $html;
    }

    private function renderFindings(array $report): string
    {
        $findings = $report['findings'] ?? [];
        if (!$findings) {
            return '';
        }

        $items = '';
        foreach ($findings as $finding) {
            $items .= '<li>' . $this->e($finding) . '</li>';
        }

        return '
        <div class="section">
            <div class="section-title">Findings</div>
            <div class="section-body"><ul>' . $items . '</ul></div>
        </div>';
    }

    private function renderNarrative(array $report): string
    {
        $narrative = $report['narrative'] ?? null;
        if (!$narrative || (trim((string)($narrative['summary'] ?? '')) === '' && empty($narrative['insights']) && empty($narrative['recommendations']))) {
            return '';
        }

        $html = '<div class="section"><div class="section-title">AI Analysis (grounded in the figures above)</div><div class="section-body">';
        if (trim((string)($narrative['summary'] ?? '')) !== '') {
            $html .= '<p>' . $this->e($narrative['summary']) . '</p>';
        }
        if (!empty($narrative['insights'])) {
            $html .= '<ul>';
            foreach ($narrative['insights'] as $insight) {
                $html .= '<li>' . $this->e($insight) . '</li>';
            }
            $html .= '</ul>';
        }
        if (!empty($narrative['recommendations'])) {
            $html .= '<div style="font-size:10px;font-weight:bold;margin-top:6px;">Recommendations</div><ul>';
            foreach ($narrative['recommendations'] as $recommendation) {
                $html .= '<li>' . $this->e($recommendation) . '</li>';
            }
            $html .= '</ul>';
        }
        $html .= '</div></div>';
        return $html;
    }

    private function renderLegacy(array $report): string
    {
        if (!array_key_exists('confidence', $report) && !array_key_exists('summary', $report) && !array_key_exists('analysis', $report)) {
            return '';
        }

        $body = '';

        if (isset($report['confidence']) && trim((string)$report['confidence']) !== '') {
            $body .= '
            <div class="section">
                <div class="section-title">AI Confidence</div>
                <div class="summary-box"><div style="font-size:14px;font-weight:bold;color:#05590c;">' . $this->e($report['confidence']) . '</div></div>
            </div>';
        }

        if (isset($report['summary']) && trim((string)$report['summary']) !== '') {
            $body .= '
            <div class="section">
                <div class="section-title">Executive Summary</div>
                <div class="section-body"><p>' . $this->e($report['summary']) . '</p></div>
            </div>';
        }

        $lists = [
            'analysis' => ['Operational Analysis', 'p'],
            'insights' => ['Key Insights', 'li'],
            'risks' => ['Risks & Concerns', 'li'],
            'recommendations' => ['Recommendations', 'li'],
        ];
        foreach ($lists as $key => [$title, $tag]) {
            if (empty($report[$key]) || !is_array($report[$key])) {
                continue;
            }
            $items = '';
            foreach ($report[$key] as $item) {
                $items .= $tag === 'p' ? '<p>' . $this->e($item) . '</p>' : '<li>' . $this->e($item) . '</li>';
            }
            $body .= '
            <div class="section">
                <div class="section-title">' . $title . '</div>
                <div class="section-body">' . ($tag === 'li' ? '<ul>' . $items . '</ul>' : $items) . '</div>
            </div>';
        }

        return $body;
    }

    private function buildBody(array $report): string
    {
        $metaRows = $this->renderMeta($report);

        $body = '';
        if ($metaRows !== '') {
            $body .= '
            <div class="section">
                <div class="section-title">Report Details</div>
                <table>' . $metaRows . '</table>
            </div>';
        }

        $body .= $this->renderKpis($report);
        $body .= $this->renderComparison($report);
        if (!empty($report['report_center'])) {
            $body .= ReportCenterPresentationService::pdfCharts($report['charts'] ?? []);
            $body .= $this->renderFindings($report);
        }

        if (!empty($report['description']) && !empty($report['meta'])) {
            $body .= '
            <div class="section">
                <div class="section-title">About This Report</div>
                <div class="section-body"><p>' . $this->e($report['description']) . '</p></div>
            </div>';
        }

        $tables = $report['tables'] ?? [];
        foreach ($tables as $table) {
            $body .= $this->renderTable(
                (string)($table['title'] ?? 'Records'),
                $table['columns'] ?? [],
                $table['rows'] ?? []
            );
        }

        $body .= $this->renderDistributions($report);
        $body .= $this->renderTrends($report);
        if (empty($report['report_center'])) $body .= $this->renderFindings($report);
        $body .= $this->renderNarrative($report);
        $body .= $this->renderLegacy($report);
        if (!empty($report['report_center']) && !empty($report['data_basis'])) {
            $body .= '<div class="section"><div class="section-title">Data sources and supporting evidence</div><ul>';
            foreach ($report['data_basis'] as $note) $body .= '<li>' . $this->e($note) . '</li>';
            $body .= '</ul></div>';
        }

        if ($body === '') {
            $body = '<div class="section"><div class="section-body"><p>No report content was produced.</p></div></div>';
        }

        return $body;
    }

    public function generate(
        string $title,
        array $report
    ): string {
        $category = strtolower(
            trim((string)($report['category'] ?? 'general'))
        );

        $directory = $_SERVER['DOCUMENT_ROOT'] . '/generated_reports/' . $category;

        if (!is_dir($directory)) {
            mkdir($directory, 0777, true);
        }

        $bodyContent = $this->buildBody($report);

        $meta = ['Generated: ' . date('F d, Y h:i A')];

        $periodLabel = (string)($report['meta']['period_label'] ?? '');
        if ($periodLabel !== '') {
            $meta[] = 'Period: ' . $periodLabel;
        }

        $recordCount = $report['meta']['record_count'] ?? null;
        if ($recordCount !== null && $recordCount !== '') {
            $meta[] = 'Records: ' . (string)$recordCount;
        }

        if (!empty($report['report_center'])) {
            $html = ReportCenterPresentationService::document($title, $report, $bodyContent);
        } else {
            $html = renderPdfHtml(
                title: $title,
                bodyContent: $bodyContent,
                orgSub: 'AI Generated Operational Report',
                meta: $meta
            );
        }

        $this->dompdf->loadHtml($html);
        $this->dompdf->setPaper('A4', 'portrait');
        $this->dompdf->render();

        $safeTitle = preg_replace('/[^A-Za-z0-9_\-]/', '_', $title);
        $filename = $safeTitle . '_' . date('Ymd_His') . '.pdf';
        $path = $directory . '/' . $filename;

        file_put_contents($path, $this->dompdf->output());

        return '/generated_reports/' . $category . '/' . $filename;
    }
}
