<?php

declare(strict_types=1);

namespace Admin\Models;

require_once $_SERVER['DOCUMENT_ROOT']
. '/app/Core/Database.php';

use App\Core\Database;
use PDO;
use Exception;

class ArchiveReportsModel
{
    /*
    |--------------------------------------------------------------------------
    | DATABASE
    |--------------------------------------------------------------------------
    */

    private PDO $db;

    /*
    |--------------------------------------------------------------------------
    | CONSTRUCTOR
    |--------------------------------------------------------------------------
    */

    public function __construct()
    {
        $this->db =
            Database::get();
    }

    /*
    |--------------------------------------------------------------------------
    | ARCHIVE REPORTS
    |--------------------------------------------------------------------------
    */

    public function archiveReports(
        ?string $year = null,
        ?string $month = null
    ): array
    {
        try {

            /*
            |--------------------------------------------------------------------------
            | TABLES
            |--------------------------------------------------------------------------
            */

$tables = [

    [
        'table' =>
            'ai_trip_operations_reports',

        'date_column' =>
            'generated_at'
    ],

    [
        'table' =>
            'trip_operations_reports',

        'date_column' =>
            'created_at'
    ],

    [
        'table' =>
            'trip_operation_evidences',

        'date_column' =>
            'created_at'
    ],

    [
        'table' =>
            'passenger_trip_history',

        'date_column' =>
            'trip_date'
    ]
];


            /*
            |--------------------------------------------------------------------------
            | RESULTS
            |--------------------------------------------------------------------------
            */

            $results = [];

            /*
            |--------------------------------------------------------------------------
            | LOOP TABLES
            |--------------------------------------------------------------------------
            */

            foreach($tables as $config){

                $table =
                    $config['table'];

                $dateColumn =
                    $config['date_column'];

                /*
                |--------------------------------------------------------------------------
                | CHECK ARCHIVED COLUMN
                |--------------------------------------------------------------------------
                */

                $check = $this->db->prepare("
                    SHOW COLUMNS
                    FROM {$table}
                    LIKE 'archived'
                ");

                $check->execute();

                /*
                |--------------------------------------------------------------------------
                | CREATE COLUMN
                |--------------------------------------------------------------------------
                */

                if(!$check->fetch()){

                    $this->db->exec("
                        ALTER TABLE {$table}

                        ADD archived TINYINT(1)
                        DEFAULT 0
                    ");
                }

                /*
                |--------------------------------------------------------------------------
                | QUERY
                |--------------------------------------------------------------------------
                */

                $query = "

                    UPDATE {$table}

                    SET archived = 1

                    WHERE archived = 0
                ";

                $params = [];

                /*
                |--------------------------------------------------------------------------
                | YEAR FILTER
                |--------------------------------------------------------------------------
                */

                if($year){

                    $query .= "

                        AND YEAR({$dateColumn}) = :year
                    ";

                    $params['year'] =
                        (int)$year;
                }

                /*
                |--------------------------------------------------------------------------
                | MONTH FILTER
                |--------------------------------------------------------------------------
                */

                if($month){

                    $query .= "

                        AND MONTH({$dateColumn}) = :month
                    ";

                    $params['month'] =
                        (int)$month;
                }

                /*
                |--------------------------------------------------------------------------
                | EXECUTE
                |--------------------------------------------------------------------------
                */

                $stmt =
                    $this->db->prepare($query);

                $stmt->execute($params);

                /*
                |--------------------------------------------------------------------------
                | RESULT
                |--------------------------------------------------------------------------
                */

                $results[] = [

                    'table' =>
                        $table,

                    'affected_rows' =>
                        $stmt->rowCount()
                ];
            }

            /*
            |--------------------------------------------------------------------------
            | DIRECTORIES
            |--------------------------------------------------------------------------
            */

            $generatedDir =

                $_SERVER['DOCUMENT_ROOT']
                .
                '/generated_reports/';

            $archiveDir =

                $_SERVER['DOCUMENT_ROOT']
                .
                '/archived_reports/';

            /*
            |--------------------------------------------------------------------------
            | CREATE ARCHIVE DIR
            |--------------------------------------------------------------------------
            */

            if(!is_dir($archiveDir)){

                mkdir(
                    $archiveDir,
                    0777,
                    true
                );
            }

            /*
            |--------------------------------------------------------------------------
            | PDF FILES
            |--------------------------------------------------------------------------
            */

            $files = glob(
                $generatedDir
                .
                '*.pdf'
            );

            $archivedFiles = [];

            /*
            |--------------------------------------------------------------------------
            | LOOP FILES
            |--------------------------------------------------------------------------
            */

            foreach($files as $file){

/*
|--------------------------------------------------------------------------
| DEFAULT
|--------------------------------------------------------------------------
*/

$fileYear = null;

$fileMonth = null;

/*
|--------------------------------------------------------------------------
| FILENAME
|--------------------------------------------------------------------------
*/

$fileName =
    basename($file);

/*
|--------------------------------------------------------------------------
| EXTRACT FIRST YYYY_MM ONLY
|--------------------------------------------------------------------------
*/

preg_match(

    '/(20\d{2})_(0[1-9]|1[0-2])/',

    $fileName,

    $matches
);


/*
|--------------------------------------------------------------------------
| FOUND
|--------------------------------------------------------------------------
*/

if(
    isset($matches[1])
    &&
    isset($matches[2])
){

    $fileYear =
        (string)$matches[1];

    $fileMonth =
        (string)$matches[2];
}

/*
|--------------------------------------------------------------------------
| INVALID FILE
|--------------------------------------------------------------------------
*/

else {

    continue;
}

/*
|--------------------------------------------------------------------------
| STRICT YEAR FILTER
|--------------------------------------------------------------------------
*/

if(
    $year
    &&
    (string)$fileYear !== (string)$year
){

    continue;
}

/*
|--------------------------------------------------------------------------
| STRICT MONTH FILTER
|--------------------------------------------------------------------------
*/

if(
    $month
    &&
    (string)$fileMonth !== str_pad(
        (string)$month,
        2,
        '0',
        STR_PAD_LEFT
    )
){

    continue;
}

                /*
                |--------------------------------------------------------------------------
                | DESTINATION
                |--------------------------------------------------------------------------
                */

                $destination =

                    $archiveDir
                    .
                    basename($file);

                /*
                |--------------------------------------------------------------------------
                | MOVE
                |--------------------------------------------------------------------------
                */
                
                

                rename(
                    $file,
                    $destination
                );

                /*
                |--------------------------------------------------------------------------
                | RESULT
                |--------------------------------------------------------------------------
                */

                $archivedFiles[] = [

                    'name' =>
                        basename($file),

                    'year' =>
                        $fileYear,

                    'month' =>
                        $fileMonth
                ];
            }

            /*
            |--------------------------------------------------------------------------
            | RETURN
            |--------------------------------------------------------------------------
            */

            return [

                'success' => true,

                'message' =>

                    'Reports archived successfully.',

                'tables' =>
                    $results,

                'files' =>
                    $archivedFiles
            ];
        }

        catch(Exception $e){

            return [

                'success' => false,

                'message' =>
                    $e->getMessage()
            ];
        }
    }

    /*
    |--------------------------------------------------------------------------
    | GET ARCHIVED FILES
    |--------------------------------------------------------------------------
    */

    public function getArchivedFiles(): array
    {
        $archiveDir =

            $_SERVER['DOCUMENT_ROOT']
            .
            '/archived_reports/';

        if(!is_dir($archiveDir)){

            return [];
        }

        $files = glob(
            $archiveDir
            .
            '*.pdf'
        );

        return array_map(

            function($file){

                return [

                    'name' =>
                        basename($file),

                    'path' =>
                        '/archived_reports/'
                        .
                        basename($file),

                    'size' =>
                        round(
                            filesize($file)
                            /
                            1024,
                            2
                        )
                        .
                        ' KB',

                    'date' =>
                        date(
                            'F d, Y',
                            filemtime($file)
                        )
                ];
            },

            $files
        );
    }

    /*
    |--------------------------------------------------------------------------
    | RESTORE FILE
    |--------------------------------------------------------------------------
    */

    public function restoreFile(
        string $file
    ): bool
    {
        $archiveFile =

            $_SERVER['DOCUMENT_ROOT']
            .
            '/archived_reports/'
            .
            $file;

        $restoreFile =

            $_SERVER['DOCUMENT_ROOT']
            .
            '/generated_reports/'
            .
            $file;

        if(!file_exists($archiveFile)){

            return false;
        }

        return rename(
            $archiveFile,
            $restoreFile
        );
    }
}
