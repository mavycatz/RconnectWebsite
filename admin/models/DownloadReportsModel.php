<?php

declare(strict_types=1);

namespace Admin\Models;

require_once $_SERVER['DOCUMENT_ROOT']
. '/app/Core/Database.php';

use App\Core\Database;
use PDO;

class DownloadReportsModel
{
    /*
    |--------------------------------------------------------------------------
    | DATABASE
    |--------------------------------------------------------------------------
    */

    private PDO $db;

    /*
    |--------------------------------------------------------------------------
    | CONSTRUCTOR
    |--------------------------------------------------------------------------
    */

    public function __construct()
    {
        $this->db = Database::get();
    }

    /*
    |--------------------------------------------------------------------------
    | GENERATED REPORT FILES
    |--------------------------------------------------------------------------
    */

    public function getGeneratedReports(): array
    {
        /*
        |--------------------------------------------------------------------------
        | REPORT DIRECTORY
        |--------------------------------------------------------------------------
        */

        $directory =

            $_SERVER['DOCUMENT_ROOT']
            .
            '/generated_reports/';

        /*
        |--------------------------------------------------------------------------
        | CHECK
        |--------------------------------------------------------------------------
        */

        if(!is_dir($directory)){

            return [];
        }

        /*
        |--------------------------------------------------------------------------
        | FILES
        |--------------------------------------------------------------------------
        */

        $files = glob(
            $directory . '*.pdf'
        );

        return $files ?: [];
    }

    /*
    |--------------------------------------------------------------------------
    | REPORT TABLES
    |--------------------------------------------------------------------------
    */

    public function getReportTables(): array
    {
        /*
        |--------------------------------------------------------------------------
        | TABLE CONFIGURATION
        |--------------------------------------------------------------------------
        */

        $tables = [

            /*
            |--------------------------------------------------------------------------
            | AI TRIP OPERATION ANALYSIS
            |--------------------------------------------------------------------------
            */

            [
                'table' =>

                    'ai_trip_operations_reports',

                'title' =>

                    'AI Trip Operation Analysis Report',

                'file_name' =>

                    'AI_Trip_Operation_Analysis_Report',

                'columns' => [

                    'report_title',
                    'trip_report_id',
                    'trip_group_code',
                    'ai_summary',
                    'ai_category',
                    'ai_confidence',
                    'ai_analysis',
                    'ai_insights',
                    'ai_risks',
                    'ai_recommendations',
                    'generated_at'
                ]
            ],

            /*
            |--------------------------------------------------------------------------
            | TRIP OPERATIONS REPORTS
            |--------------------------------------------------------------------------
            */

            [
                'table' =>

                    'trip_operations_reports',

                'title' =>

                    'Trip Operations Report',

                'file_name' =>

                    'Trip_Operations_Report',

                'columns' => [

                    'trip_id',
                    'terminal_code_1',
                    'terminal_code_2',
                    'departure_time',
                    'arrival_time',
                    'total_passengers',
                    'pao_name',
                    'pao_signature',
                    'driver_name',
                    'driver_signature',
                    'remarks',
                    'created_at'
                ]
            ],

            /*
            |--------------------------------------------------------------------------
            | TRIP OPERATION EVIDENCES
            |--------------------------------------------------------------------------
            */

            [
                'table' =>

                    'trip_operation_evidences',

                'title' =>

                    'Trip Operation Evidences Report',

                'file_name' =>

                    'Trip_Operation_Evidences_Report',

                'columns' => [

                    'trip_id',
                    'terminal_code_1',
                    'terminal_code_2',
                    'departure_time',
                    'arrival_time',
                    'total_passengers',
                    'pao_name',
                    'pao_signature',
                    'driver_name',
                    'driver_signature',
                    'remarks',
                    'created_at'
                ]
            ],

            /*
            |--------------------------------------------------------------------------
            | PASSENGER TRIP HISTORY
            |--------------------------------------------------------------------------
            */

            [
                'table' =>

                    'passenger_trip_history',

                'title' =>

                    'Passenger Trip History Report',

                'file_name' =>

                    'Passenger_Trip_History_Report',

                'columns' => [

                    'passenger_id',
                    'passenger_type',
                    'student_id',
                    'boarding_point',
                    'destination',
                    'bus_number',
                    'trip_id',
                    'fare',
                    'payment_method',
                    'date_booked',
                    'trip_date',
                    'archived_at',
                    'senior_pwd_id',
                    'beneficiary_id',
                    'coop_disc_id',
                    'remarks'
                ]
            ]
        ];

        /*
        |--------------------------------------------------------------------------
        | RESULTS
        |--------------------------------------------------------------------------
        */

        $results = [];

        /*
        |--------------------------------------------------------------------------
        | LOOP TABLES
        |--------------------------------------------------------------------------
        */

        foreach($tables as $config){

            /*
            |--------------------------------------------------------------------------
            | QUERY
            |--------------------------------------------------------------------------
            */

            $stmt = $this->db->prepare("
                SELECT *
                FROM {$config['table']}
                ORDER BY 1 DESC
            ");

            $stmt->execute();

            /*
            |--------------------------------------------------------------------------
            | RECORDS
            |--------------------------------------------------------------------------
            */

            $records =

                $stmt->fetchAll(
                    PDO::FETCH_ASSOC
                );

            /*
            |--------------------------------------------------------------------------
            | TOTAL RECORDS
            |--------------------------------------------------------------------------
            */

            $totalRecords =

                count($records);

            /*
            |--------------------------------------------------------------------------
            | LAST GENERATED
            |--------------------------------------------------------------------------
            */

            $lastGenerated =

                $records[0]['generated_at']

                ??

                $records[0]['created_at']

                ??

                null;

            /*
            |--------------------------------------------------------------------------
            | PUSH RESULT
            |--------------------------------------------------------------------------
            */

            $results[] = [

                /*
                |--------------------------------------------------------------------------
                | TABLE NAME
                |--------------------------------------------------------------------------
                */

                'table' =>

                    $config['table'],

                /*
                |--------------------------------------------------------------------------
                | TITLE
                |--------------------------------------------------------------------------
                */

                'title' =>

                    $config['title'],

                /*
                |--------------------------------------------------------------------------
                | EXPORT FILE NAME
                |--------------------------------------------------------------------------
                */

                'file_name' =>

                    $config['file_name'],

                /*
                |--------------------------------------------------------------------------
                | TOTAL RECORDS
                |--------------------------------------------------------------------------
                */

                'total_records' =>

                    $totalRecords,

                /*
                |--------------------------------------------------------------------------
                | LAST GENERATED
                |--------------------------------------------------------------------------
                */

                'last_generated' =>

                    $lastGenerated,

                /*
                |--------------------------------------------------------------------------
                | INCLUDED COLUMNS
                |--------------------------------------------------------------------------
                */

                'columns' =>

                    $config['columns'],

                /*
                |--------------------------------------------------------------------------
                | RECORDS
                |--------------------------------------------------------------------------
                */

                'records' =>

                    $records
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | RETURN
        |--------------------------------------------------------------------------
        */

        return $results;
    }
}