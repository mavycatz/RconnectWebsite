declare(strict_types=1);

error_reporting(0);
ini_set('display_errors', '0');
ob_start();

require_once $_SERVER['DOCUMENT_ROOT'] . '/app/Core/Bootstrap.php';

use App\Auth\Session;
use App\Auth\Auth;

Session::start();

if (!Auth::check()) {
    send_json(['success' => false, 'message' => 'Unauthorized'], 401);
}

$user = Auth::user();
if (!isset($user['role']) || !in_array(strtolower($user['role']), ['admin', 'super_admin'])) {
    send_json(['success' => false, 'message' => 'Forbidden'], 403);
}

function send_json($data, int $code = 200): void
{
    if (ob_get_level() > 0) {
        ob_end_clean();
    }
    header('Content-Type: application/json');
    if ($code !== 200) {
        http_response_code($code);
    }
    echo json_encode($data);
    exit;
}
require_once $_SERVER['DOCUMENT_ROOT'] . '/app/Core/Database.php';
require_once __DIR__ . '/driver-perf-metrics-core.php';
require_once __DIR__ . '/driver-ai-core.php';

use App\Core\Database;

/**
 * Write a Driver Performance report export to the system audit log.
 */
function dpa_report_audit(string $driverId, string $driverName, string $periodLabel, string $format, string $username, array $extra = []): void
{
    try {
        require_once $_SERVER['DOCUMENT_ROOT'] . '/app/services/AuditService.php';
        \AuditService::log(
            'Driver Performance',
            'Report Exported',
            "Exported {$format} performance report for {$driverName} ({$driverId}) | {$periodLabel}",
            $driverId,
            null,
            array_merge(['format' => $format, 'generated_by' => $username], $extra),
            'Success'
        );
    } catch (\Throwable $e) {
        error_log('Audit log error (report export): ' . $e->getMessage());
    }
}

$format = strtolower(trim((string)($_GET['format'] ?? 'pdf')));
$driverId = trim((string)($_GET['driver_id'] ?? ''));

if (!in_array($format, ['pdf', 'excel'], true)) {
    send_json(['success' => false, 'message' => 'Invalid format'], 400);
}
if (!$driverId) {
    send_json(['success' => false, 'message' => 'Driver ID missing'], 400);
}

try {
    $db = Database::get();
    [$start, $end, $period] = dpm_period_range($_GET);
    $periodLabel = dpm_period_label($period, $start, $end);
    $periodSlug = str_replace('_', '-', $period);

    $actor = Auth::user() ?: [];
    $generatedBy = (string)($actor['username'] ?? $actor['name'] ?? 'admin');
    $generatedByRole = (string)($actor['role'] ?? '');
    $generatedAt = date('Y-m-d H:i:s');
    $exportedLine = 'Generated by ' . $generatedBy . ($generatedByRole !== '' ? ' (' . $generatedByRole . ')' : '') . ' on ' . $generatedAt;

    if ($format === 'excel') {
        $m = dpm_compute($db, $driverId, $start, $end, $period);
        if (isset($m['error'])) {
            send_json(['success' => false, 'message' => $m['error']]);
        }
        require_once $_SERVER['DOCUMENT_ROOT'] . '/admin/services/ExcelService.php';
        $svc = new Admin\Services\ExcelService();
        $title = 'Driver_Report_' . preg_replace('/[^A-Za-z0-9]/', '', $m['driver_id']) . '_' . $periodSlug;
        $url = $svc->generate($title, $m + ['period' => $period, 'period_label' => $periodLabel, 'generated_by' => $generatedBy]);
        dpa_report_audit($driverId, (string)($m['name'] ?? $driverId), $periodLabel, strtoupper($format), $generatedBy, ['start' => $start, 'end' => $end]);
        send_json(['success' => true, 'url' => $url, 'generated_by' => $generatedBy, 'generated_at' => $generatedAt, 'period_label' => $periodLabel]);
    }

    $result = dpm_build_analysis($db, $driverId, $start, $end, $period);
    if (isset($result['error'])) {
        send_json(['success' => false, 'message' => $result['error']]);
    }
    $m = $result['metrics'];
    $a = $result['analysis'];

    require_once $_SERVER['DOCUMENT_ROOT'] . '/admin/services/PDFService.php';
    $svc = new Admin\Services\PDFService();
    $title = trim((string)($m['name'] ?? 'Driver')) . ' - Performance Report';
    $report = [
        'category' => 'driver_report',
        'confidence' => $periodLabel . ' | ' . $exportedLine . ' | Generated from verified backend metrics',
        'summary' => $a['summary'] ?? '',
        'analysis' => array_filter([$a['strengths'] ?? ''], fn($x) => trim($x) !== ''),
        'insights' => array_filter([$a['watch_outs'] ?? '', $a['key_findings'] ?? ''], fn($x) => trim($x) !== ''),
        'risks' => [],
        'recommendations' => array_filter([$a['recommendation'] ?? ''], fn($x) => trim($x) !== ''),
    ];
    $url = $svc->generate($title, $report);
    dpa_report_audit($driverId, (string)($m['name'] ?? $driverId), $periodLabel, strtoupper($format), $generatedBy, ['start' => $start, 'end' => $end]);
    send_json(['success' => true, 'url' => $url, 'generated_by' => $generatedBy, 'generated_at' => $generatedAt, 'period_label' => $periodLabel]);
} catch (Throwable $e) {
    send_json(['success' => false, 'error' => $e->getMessage(), 'line' => $e->getLine()]);
}
