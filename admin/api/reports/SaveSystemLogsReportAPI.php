<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| ERRORS
|--------------------------------------------------------------------------
*/

ini_set('display_errors', '1');

ini_set('display_startup_errors', '1');

error_reporting(E_ALL);

/*
|--------------------------------------------------------------------------
| JSON
|--------------------------------------------------------------------------
*/

header('Content-Type: application/json');

/*
|--------------------------------------------------------------------------
| DOMPDF
|--------------------------------------------------------------------------
*/

require_once $_SERVER['DOCUMENT_ROOT']
. '/vendor/autoload.php';

require_once $_SERVER['DOCUMENT_ROOT']
. '/app/auth/Session.php';
\App\Auth\Session::start();

require_once $_SERVER['DOCUMENT_ROOT']
. '/finance/models/AuditTrailModel.php';

use Dompdf\Dompdf;
use Dompdf\Options;
use Finance\Models\AuditTrailModel;

try {

    /*
    |--------------------------------------------------------------------------
    | INPUT
    |--------------------------------------------------------------------------
    */

    $data = json_decode(

        file_get_contents(
            'php://input'
        ),

        true
    );

    /*
    |--------------------------------------------------------------------------
    | HTML
    |--------------------------------------------------------------------------
    */

    $html =

        $data['html']
        ??
        '';

    /*
    |--------------------------------------------------------------------------
    | EMPTY
    |--------------------------------------------------------------------------
    */

    if(!$html){

        throw new Exception(
            'No report content received.'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | DIRECTORY
    |--------------------------------------------------------------------------
    */

    $directory =

        $_SERVER['DOCUMENT_ROOT']

        .

        '/generated_reports/';

    /*
    |--------------------------------------------------------------------------
    | CREATE DIR
    |--------------------------------------------------------------------------
    */

    if(!is_dir($directory)){

        mkdir(

            $directory,

            0777,

            true
        );
    }

    /*
    |--------------------------------------------------------------------------
    | DATE
    |--------------------------------------------------------------------------
    */

    $date =

        date(
            'Y_m_d_His'
        );

    /*
    |--------------------------------------------------------------------------
    | FILENAME
    |--------------------------------------------------------------------------
    */

    $filename =

        'System_Activity_Summary_'

        .

        $date

        .

        '.pdf';

    /*
    |--------------------------------------------------------------------------
    | FULL PATH
    |--------------------------------------------------------------------------
    */

    $fullPath =

        $directory

        .

        $filename;

    /*
    |--------------------------------------------------------------------------
    | DOMPDF OPTIONS
    |--------------------------------------------------------------------------
    */

    $options =
        new Options();

    $options->set(

        'isRemoteEnabled',

        true
    );

    /*
    |--------------------------------------------------------------------------
    | DOMPDF
    |--------------------------------------------------------------------------
    */

    $dompdf =
        new Dompdf($options);

    /*
    |--------------------------------------------------------------------------
    | LOAD HTML
    |--------------------------------------------------------------------------
    */

    $dompdf->loadHtml(
        $html
    );

    /*
    |--------------------------------------------------------------------------
    | PAPER
    |--------------------------------------------------------------------------
    */

    $dompdf->setPaper(

        'A4',

        'portrait'
    );

    /*
    |--------------------------------------------------------------------------
    | RENDER
    |--------------------------------------------------------------------------
    */

    $dompdf->render();

    /*
    |--------------------------------------------------------------------------
    | SAVE PDF
    |--------------------------------------------------------------------------
    */

    file_put_contents(

        $fullPath,

        $dompdf->output()
    );

    /*
    |--------------------------------------------------------------------------
    | AUDIT LOG
    |--------------------------------------------------------------------------
    */

    $audit = new AuditTrailModel();
    $audit->log('Reports', 'Export', 'Exported system logs report to PDF: ' . $filename,
        $_SESSION['user']['id'] ?? null,
        $_SESSION['user']['username'] ?? null,
        $_SESSION['user']['role'] ?? null
    );

    /*
    |--------------------------------------------------------------------------
    | RESPONSE
    |--------------------------------------------------------------------------
    */

    echo json_encode([
        'success' => true,
        'message' => 'System logs report saved successfully.',
        'file' => '/generated_reports/' . $filename
    ]);

    exit;
}

catch(Throwable $e){

    try {
        $audit = new AuditTrailModel();
        $audit->log('Reports', 'Export', 'Failed to export system logs report: ' . $e->getMessage(),
            $_SESSION['user']['id'] ?? null,
            $_SESSION['user']['username'] ?? null,
            $_SESSION['user']['role'] ?? null,
            null, null, 'Failed'
        );
    } catch (Throwable $ignore) {}

    echo json_encode([
        'success' => false,
        'message' => $e->getMessage()
    ]);

    exit;
}

