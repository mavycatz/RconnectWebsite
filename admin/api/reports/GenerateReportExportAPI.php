<?php declare(strict_types=1);

/**
 * Generate Report CSV export endpoint.
 *
 * Writes the filtered dataset (with metadata header rows) as a CSV under
 * generated_reports/<category>/ so it appears in the existing report library,
 * and returns its URL. Admin/super_admin only; audited.
 */

require_once $_SERVER['DOCUMENT_ROOT'] . '/admin/api/reports/_library.php';
require_once $_SERVER['DOCUMENT_ROOT'] . '/admin/api/reports/report_types.php';
require_once $_SERVER['DOCUMENT_ROOT'] . '/admin/api/reports/report_builder.php';

use Finance\Models\AuditTrailModel;

date_default_timezone_set('Asia/Manila');

$user = rlib_guard();

function rgen_export_audit(string $description, array $user, array $extra, string $status = 'Success'): void
{
    try {
        require_once $_SERVER['DOCUMENT_ROOT'] . '/finance/models/AuditTrailModel.php';
        $audit = new AuditTrailModel();
        $audit->log(
            'Reports',
            'Export',
            $description,
            isset($user['id']) ? (int)$user['id'] : null,
            $user['username'] ?? null,
            $user['role'] ?? null,
            null,
            $extra,
            $status
        );
    } catch (Throwable $ignore) {
    }
}

function rgen_csv_value($value, string $type): string
{
    $raw = trim((string)($value ?? ''));
    if ($raw === '' || str_starts_with($raw, '0000-00-00')) {
        return '';
    }
    switch ($type) {
        case 'money':
            return number_format((float)$raw, 2, '.', '');
        case 'date':
            try {
                return (new DateTime($raw, new DateTimeZone('Asia/Manila')))->format('Y-m-d');
            } catch (Throwable $e) {
                return $raw;
            }
        case 'datetime':
            try {
                return (new DateTime($raw, new DateTimeZone('Asia/Manila')))->format('Y-m-d H:i:s');
            } catch (Throwable $e) {
                return $raw;
            }
        default:
            return $raw;
    }
}

$input = json_decode(file_get_contents('php://input'), true);
if (!is_array($input)) {
    $input = $_POST ?: $_GET;
}

$reportType = trim((string)($input['report_type'] ?? ''));
$format = strtolower(trim((string)($input['format'] ?? 'csv')));
if ($reportType === '') {
    rlib_respond(['success' => false, 'message' => 'Report type is required.'], 400);
}
if ($format !== 'csv') {
    rlib_respond(['success' => false, 'message' => 'Unsupported export format.'], 400);
}

try {
    $report = rgen_build_report($reportType, $input, $user, false);

    $category = preg_replace('/[^a-z0-9_\-]/', '', strtolower((string)$report['category'])) ?: 'general';
    $directory = $_SERVER['DOCUMENT_ROOT'] . '/generated_reports/' . $category;
    if (!is_dir($directory)) {
        mkdir($directory, 0777, true);
    }

    $safeTitle = substr(preg_replace('/[^A-Za-z0-9_\-]/', '_', (string)$report['title']), 0, 90);
    $filename = $safeTitle . '_' . date('Ymd_His') . '.csv';
    $path = $directory . '/' . $filename;

    $handle = fopen($path, 'w');
    if ($handle === false) {
        throw new RuntimeException('Could not create the export file.');
    }

    $period = $report['period'] ?? null;
    $filterParts = [];
    foreach ($report['applied_filters'] as $filter) {
        $filterParts[] = (string)($filter['label'] ?? '') . ': ' . (string)($filter['value'] ?? '');
    }

    fputcsv($handle, ['Report', $report['title']]);
    fputcsv($handle, ['Report type', $report['type_label']]);
    fputcsv($handle, ['Covered period', $period ? (string)$period['label'] : 'All records']);
    fputcsv($handle, ['Covered dates', $period ? ($period['start_date'] . ' to ' . $period['end_date']) : '']);
    fputcsv($handle, ['Generated', rgen_datetime((string)$report['generated_at']) . ' (PHT)']);
    fputcsv($handle, ['Generated by', (string)$report['generated_by']]);
    fputcsv($handle, ['Records', (string)$report['record_count']]);
    fputcsv($handle, ['Applied filters', implode('; ', $filterParts)]);
    fputcsv($handle, []);

    fputcsv($handle, array_map(static fn ($c) => (string)($c['label'] ?? $c['key'] ?? ''), $report['columns']));
    foreach ($report['records'] as $row) {
        $line = [];
        foreach ($report['columns'] as $column) {
            $line[] = rgen_csv_value($row[$column['key'] ?? ''] ?? null, (string)($column['type'] ?? 'text'));
        }
        fputcsv($handle, $line);
    }
    fclose($handle);

    $url = '/generated_reports/' . $category . '/' . $filename;

    rgen_export_audit(
        'Exported CSV report: ' . $report['title'] . ' (' . $report['record_count'] . ' records)',
        $user,
        ['report_type' => $reportType, 'format' => 'CSV', 'file' => $url]
    );

    rlib_respond([
        'success' => true,
        'data' => [
            'report_type' => $reportType,
            'title' => $report['title'],
            'record_count' => $report['record_count'],
            'url' => $url,
        ],
    ]);
} catch (InvalidArgumentException $e) {
    rlib_respond(['success' => false, 'message' => $e->getMessage()], 400);
} catch (Throwable $e) {
    error_log('GenerateReportExportAPI: ' . $e->getMessage());
    rgen_export_audit('Failed CSV export: ' . $e->getMessage(), $user, ['report_type' => $reportType], 'Failed');
    rlib_respond(['success' => false, 'message' => 'Export failed: ' . $e->getMessage()], 500);
}
