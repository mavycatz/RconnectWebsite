<?php

declare(strict_types=1);

namespace Admin\Controllers;

/*
|--------------------------------------------------------------------------
| DEBUG
|--------------------------------------------------------------------------
*/

ini_set('display_errors', '1');

ini_set('display_startup_errors', '1');

error_reporting(E_ALL);

/*
|--------------------------------------------------------------------------
| AUTOLOAD
|--------------------------------------------------------------------------
*/

require_once $_SERVER['DOCUMENT_ROOT']
. '/vendor/autoload.php';
require_once $_SERVER['DOCUMENT_ROOT']
. '/app/views/pdf/template.php';

/*
|--------------------------------------------------------------------------
| MODEL
|--------------------------------------------------------------------------
*/

require_once $_SERVER['DOCUMENT_ROOT']
. '/admin/models/DownloadReportsModel.php';

use Admin\Models\DownloadReportsModel;
use Dompdf\Dompdf;
use Dompdf\Options;
use ZipArchive;
use Exception;
use Throwable;

class DownloadReportsController
{
    /*
    |--------------------------------------------------------------------------
    | MODEL
    |--------------------------------------------------------------------------
    */

    private DownloadReportsModel $model;

    /*
    |--------------------------------------------------------------------------
    | CONSTRUCTOR
    |--------------------------------------------------------------------------
    */

    public function __construct()
    {
        $this->model =
            new DownloadReportsModel();
    }

    /*
    |--------------------------------------------------------------------------
    | DOWNLOAD
    |--------------------------------------------------------------------------
    */

public function download(): string
{
    try {

        /*
        |--------------------------------------------------------------------------
        | MEMORY
        |--------------------------------------------------------------------------
        */

        ini_set(
            'memory_limit',
            '512M'
        );

        set_time_limit(300);

        /*
        |--------------------------------------------------------------------------
        | TABLES
        |--------------------------------------------------------------------------
        */

        $tables =
            $this->model
            ->getReportTables();

        /*
        |--------------------------------------------------------------------------
        | EMPTY
        |--------------------------------------------------------------------------
        */

        if(empty($tables)){

            throw new Exception(
                'No report tables found.'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | DIRECTORY
        |--------------------------------------------------------------------------
        */

        $reportDirectory =

            $_SERVER['DOCUMENT_ROOT']
            .
            '/generated_reports/';

        /*
        |--------------------------------------------------------------------------
        | CREATE DIRECTORY
        |--------------------------------------------------------------------------
        */

        if(!is_dir($reportDirectory)){

            mkdir(
                $reportDirectory,
                0777,
                true
            );
        }

        /*
        |--------------------------------------------------------------------------
        | GENERATE PDFS
        |--------------------------------------------------------------------------
        */

        foreach($tables as $report){

            /*
            |--------------------------------------------------------------------------
            | HTML
            |--------------------------------------------------------------------------
            */

            $bodyContent = '

            <div class="section">

                <div class="section-title">' . htmlspecialchars($report['title']) . '</div>

            <table>

            <thead>

            <tr style="
                background:#f3f4f6;
            ">
            ';

            /*
            |--------------------------------------------------------------------------
            | HEADERS
            |--------------------------------------------------------------------------
            */

            foreach($report['columns'] as $column){

                $bodyContent .= '

                <th>
                    '
                    .
                    strtoupper(
                        str_replace(
                            '_',
                            ' ',
                            $column
                        )
                    )
                    .
                    '
                </th>
                ';
            }

            $bodyContent .= '

            </tr>

            </thead>

            <tbody>
            ';

            /*
            |--------------------------------------------------------------------------
            | ROWS
            |--------------------------------------------------------------------------
            */

            foreach($report['records'] as $row){

                $bodyContent .= '<tr>';

                foreach($report['columns'] as $column){

                    $value =
                        $row[$column]
                        ??
                        '';

                    /*
                    |--------------------------------------------------------------------------
                    | ARRAY FIX
                    |--------------------------------------------------------------------------
                    */

                    if(is_array($value)){

                        $value =
                            json_encode($value);
                    }

                    /*
                    |--------------------------------------------------------------------------
                    | OBJECT FIX
                    |--------------------------------------------------------------------------
                    */

                    if(is_object($value)){

                        $value =
                            json_encode($value);
                    }

                    $bodyContent .= '

                    <td>
                        '
                        .
                        htmlspecialchars(
                            (string)$value
                        )
                        .
                        '
                    </td>
                    ';
                }

                $bodyContent .= '</tr>';
            }

            $bodyContent .= '

            </tbody>

            </table>

            </div>
            ';

            /*
            |--------------------------------------------------------------------------
            | RENDER PDF
            |--------------------------------------------------------------------------
            */

            $html = renderPdfHtml(
                title: $report['title'],
                bodyContent: $bodyContent,
                orgSub: 'System Reports'
            );

            /*
            |--------------------------------------------------------------------------
            | DOMPDF
            |--------------------------------------------------------------------------
            */

            $options = new Options();
            $options->set('isRemoteEnabled', true);

            $dompdf =
                new Dompdf($options);

            $dompdf->loadHtml($html);

            $dompdf->setPaper(
                'A4',
                'landscape'
            );

            $dompdf->render();

            /*
            |--------------------------------------------------------------------------
            | FILE PATH
            |--------------------------------------------------------------------------
            */

            $pdfPath =

                $reportDirectory
                .
                $report['file_name']
                .
                '.pdf';

            /*
            |--------------------------------------------------------------------------
            | SAVE PDF
            |--------------------------------------------------------------------------
            */

            file_put_contents(
                $pdfPath,
                $dompdf->output()
            );
        }

        /*
        |--------------------------------------------------------------------------
        | ZIP FILE
        |--------------------------------------------------------------------------
        */

        $zipFile =

            $reportDirectory
            .
            'Transportation_Reports_'
            .
            time()
            .
            '.zip';

        /*
        |--------------------------------------------------------------------------
        | ZIP
        |--------------------------------------------------------------------------
        */

        $zip =
            new ZipArchive();

        /*
        |--------------------------------------------------------------------------
        | OPEN ZIP
        |--------------------------------------------------------------------------
        */

        if(

            $zip->open(
                $zipFile,
                ZipArchive::CREATE
                |
                ZipArchive::OVERWRITE
            ) !== true

        ){

            throw new Exception(
                'Failed to create ZIP.'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | PDF FILES
        |--------------------------------------------------------------------------
        */

        $pdfs =
            glob(
                $reportDirectory
                .
                '*.pdf'
            );

        /*
        |--------------------------------------------------------------------------
        | ADD FILES
        |--------------------------------------------------------------------------
        */

        foreach($pdfs as $file){

            $zip->addFile(
                $file,
                basename($file)
            );
        }

        /*
        |--------------------------------------------------------------------------
        | CLOSE ZIP
        |--------------------------------------------------------------------------
        */

        $zip->close();

        /*
        |--------------------------------------------------------------------------
        | CHECK
        |--------------------------------------------------------------------------
        */

        if(!file_exists($zipFile)){

            throw new Exception(
                'ZIP file missing.'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | RETURN
        |--------------------------------------------------------------------------
        */

        return $zipFile;
    }

    catch(Throwable $e){

        throw new Exception(
            $e->getMessage()
        );
    }
}


}

