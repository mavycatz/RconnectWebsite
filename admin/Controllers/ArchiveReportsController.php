<?php

declare(strict_types=1);

namespace Admin\Controllers;

require_once $_SERVER['DOCUMENT_ROOT']
. '/admin/models/ArchiveReportsModel.php';

use Admin\Models\ArchiveReportsModel;

class ArchiveReportsController
{
    /*
    |--------------------------------------------------------------------------
    | MODEL
    |--------------------------------------------------------------------------
    */

    private ArchiveReportsModel $model;

    /*
    |--------------------------------------------------------------------------
    | CONSTRUCTOR
    |--------------------------------------------------------------------------
    */

    public function __construct()
    {
        $this->model =
            new ArchiveReportsModel();
    }

    /*
    |--------------------------------------------------------------------------
    | ARCHIVE
    |--------------------------------------------------------------------------
    */

    public function archive(): array
    {
        /*
        |--------------------------------------------------------------------------
        | JSON INPUT
        |--------------------------------------------------------------------------
        */

        $data = json_decode(

            file_get_contents(
                'php://input'
            ),

            true
        );

        /*
        |--------------------------------------------------------------------------
        | YEAR
        |--------------------------------------------------------------------------
        */

        $year =
            $data['year']
            ??
            null;

        /*
        |--------------------------------------------------------------------------
        | MONTH
        |--------------------------------------------------------------------------
        */

        $month =
            $data['month']
            ??
            null;

        /*
        |--------------------------------------------------------------------------
        | DEBUG
        |--------------------------------------------------------------------------
        */

        error_log(
            'ARCHIVE YEAR: '
            .
            $year
        );

        error_log(
            'ARCHIVE MONTH: '
            .
            $month
        );

        /*
        |--------------------------------------------------------------------------
        | MODEL
        |--------------------------------------------------------------------------
        */

        return $this->model->archiveReports(

            $year,

            $month
        );
    }
}

